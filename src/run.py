"""End-to-end pipeline entry point.

    python -m src.run                 # all implemented phases
    python -m src.run --phases 1      # only Phase 1
    python -m src.run --config my.yaml

Phase 1: synthetic inputs -> hourly DC-OPF (with and without line limits)
         -> sanity checks -> figures -> reports/phase1_summary.{json,md}
"""
from __future__ import annotations

import argparse
import json
import time

import pandas as pd

from . import checks, plots
from .config import data_dir, load_config, reports_dir
from .simulate import DispatchResult, solve_dispatch, summarize
from .synth import generate_inputs

IMPLEMENTED_PHASES = (1,)


def save_result(res: DispatchResult, folder, prefix: str = "") -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for name, df in res.frames().items():
        df.to_parquet(folder / f"{prefix}{name}.parquet")


def load_result(folder, prefix: str = "") -> DispatchResult:
    f = {k: pd.read_parquet(folder / f"{prefix}{k}.parquet") for k in ("lmp", "flow", "loading", "binding", "dispatch")}
    return DispatchResult(**f)


def phase1(cfg: dict) -> dict:
    out_data = data_dir(cfg) / "phase1"
    out_rep = reports_dir(cfg)
    fig_dir = out_rep / "figures"

    print("[phase 1] generating synthetic inputs")
    inputs = generate_inputs(cfg)
    out_data.mkdir(parents=True, exist_ok=True)
    inputs.to_parquet(out_data / "inputs.parquet")

    print(f"[phase 1] solving DC-OPF for {len(inputs)} hours (with line limits)")
    t0 = time.perf_counter()
    res = solve_dispatch(cfg, inputs, verbose=True)
    wall = time.perf_counter() - t0
    save_result(res, out_data)

    print("[phase 1] solving copper-plate case (no line limits)")
    copper = solve_dispatch(cfg, inputs, line_limits=False)
    save_result(copper, out_data, prefix="copper_")

    print("[phase 1] sanity checks")
    chk = {
        "copper_plate_single_price": checks.check_copper_plate(copper),
        "independent_angle_dcopf_resolve": checks.check_independent_resolve(cfg, inputs, res, n_hours=200, seed=cfg["seed"]),
        "physics": checks.check_physics(cfg, inputs, res),
        "congestion_target": checks.check_congestion_target(cfg, res),
    }
    for k, v in chk.items():
        print(f"   {'PASS' if v['passed'] else 'FAIL'}  {k}")

    print("[phase 1] figures")
    figs = [
        plots.network_diagram(cfg, fig_dir),
        plots.network_diagram(cfg, fig_dir, res.binding.mean(), "share of hours at limit"),
        plots.inputs_overview(cfg, inputs, fig_dir),
        plots.spread_vs_loading(cfg, res, fig_dir),
        plots.lmp_week(cfg, res, fig_dir),
        plots.price_duration(cfg, res, fig_dir, copper),
        plots.binding_by_line(cfg, res, fig_dir),
    ]

    summary = {
        "constrained": summarize(cfg, res, inputs),
        "copper_plate": summarize(cfg, copper, inputs),
        "wall_seconds_constrained_run": wall,
        "checks": chk,
        "figures": [str(p.relative_to(out_rep.parent)) for p in figs],
    }
    with open(out_rep / "phase1_summary.json", "w") as f:
        json.dump(summary, f, indent=2)
    (out_rep / "phase1_summary.md").write_text(phase1_markdown(cfg, summary))
    print(f"[phase 1] done -> {out_rep / 'phase1_summary.md'}")
    return summary


def phase1_markdown(cfg: dict, s: dict) -> str:
    c, cp = s["constrained"], s["copper_plate"]
    lines = [
        "# Phase 1 summary (auto-generated by `python -m src.run`)",
        "",
        f"* Hours simulated: **{c['hours']:,}**; DC-OPF wall time **{s['wall_seconds_constrained_run']:.1f} s**",
        f"* Mean / peak total load: {c['mean_total_load_mw']:,.0f} / {c['peak_total_load_mw']:,.0f} MW",
        f"* Hours with ≥1 binding line: **{c['share_hours_any_binding']:.1%}** "
        f"(target {cfg['congestion_target']['min_share']:.0%}–{cfg['congestion_target']['max_share']:.0%})",
        f"* Hours with load shedding: {c['hours_with_load_shed']}",
        f"* Mean |max−min| LMP spread across Alberta buses: {c['mean_abs_spread_internal_buses']:.2f} $/MWh "
        f"(P95 {c['p95_spread_internal_buses']:.1f}); without line limits: {cp['mean_abs_spread_internal_buses']:.2e}",
        "",
        "## Binding frequency by line",
        "",
        "| line | share of hours at limit |",
        "|---|---:|",
        *[f"| {k} | {v:.1%} |" for k, v in sorted(c["share_hours_binding_by_line"].items(), key=lambda kv: -kv[1])],
        "",
        "## Mean LMP by bus ($/MWh)",
        "",
        "| bus | with line limits | no line limits |",
        "|---|---:|---:|",
        *[f"| {b} | {v:.2f} | {cp['mean_lmp_by_bus'][b]:.2f} |" for b, v in c["mean_lmp_by_bus"].items()],
        "",
        "## Energy share by technology (with line limits)",
        "",
        "| carrier | share |",
        "|---|---:|",
        *[f"| {k} | {v:.1%} |" for k, v in sorted(c["energy_share_by_carrier"].items(), key=lambda kv: -kv[1])],
        "",
        "## Sanity checks",
        "",
        "| check | result | details |",
        "|---|---|---|",
    ]
    for k, v in s["checks"].items():
        det = ", ".join(f"{dk}={dv:.3g}" if isinstance(dv, float) else f"{dk}={dv}" for dk, dv in v.items() if dk != "passed")
        lines.append(f"| {k} | {'PASS' if v['passed'] else 'FAIL'} | {det} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=None)
    ap.add_argument("--phases", default=",".join(map(str, IMPLEMENTED_PHASES)))
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    phases = [int(p) for p in args.phases.split(",")]
    for p in phases:
        if p not in IMPLEMENTED_PHASES:
            raise SystemExit(f"phase {p} not implemented yet (implemented: {IMPLEMENTED_PHASES})")
    if 1 in phases:
        phase1(cfg)


if __name__ == "__main__":
    main()
